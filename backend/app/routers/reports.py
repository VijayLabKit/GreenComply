# ---- CBAM ----

def _normalise_shipment(s: dict) -> dict:
    return {
        "id": s.get("id") or s.get("shipment_ref"),
        "product": s.get("product"),
        "tonnes": s.get("tonnes"),
        "emissionsPerTonne": s.get("emissionsPerTonne") or s.get("emissions_per_tonne"),
        "carbonCost": s.get("carbonCost") or s.get("carbon_cost"),
        "status": s.get("status"),
        "declarationDue": s.get("declarationDue") or s.get("declaration_due"),
    }


@router.get("/cbam")
def get_cbam(user: dict = Depends(get_current_user)):
    if SUPABASE_CONFIGURED:
        sb = get_supabase()
        result = sb.table("cbam_declarations").select("*").eq("company_id", user["company_id"]).order("shipment_ref").execute()
        return [_normalise_shipment(s) for s in result.data]
    return [_normalise_shipment(s) for s in CBAM_SHIPMENTS]


@router.post("/cbam/generate")
def generate_cbam(user: dict = Depends(get_current_user)):
    total_cost = sum(s["carbonCost"] for s in CBAM_SHIPMENTS)
    total_tonnes = sum(s["tonnes"] for s in CBAM_SHIPMENTS)
    record = {"company_id": user["company_id"], "shipments": CBAM_SHIPMENTS, "totalCost": total_cost, "totalTonnes": total_tonnes}
    log_activity("CBAM Q3 declaration regenerated from shipment ledger")
    if SUPABASE_CONFIGURED:
        sb = get_supabase()
        result = sb.table("cbam_declarations").select("*").eq("company_id", user["company_id"]).execute()
        shipments = [_normalise_shipment(s) for s in result.data]
        return {
            "company_id": user["company_id"],
            "shipments": shipments,
            "totalCost": sum(s["carbonCost"] or 0 for s in shipments),
            "totalTonnes": sum(s["tonnes"] or 0 for s in shipments),
        }
    return record


@router.get("/cbam/export")
def export_cbam(user: dict = Depends(get_current_user)):
    """Real CSV download in a CBAM-declaration-compatible column layout."""
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow([
        "shipment_id", "goods_description", "net_mass_tonnes",
        "embedded_emissions_tco2e_per_tonne", "carbon_cost_eur",
        "declaration_due", "status",
    ])
    for s in CBAM_SHIPMENTS:
        writer.writerow([
            s["id"], s["product"], s["tonnes"], s["emissionsPerTonne"],
            s["carbonCost"], s["declarationDue"], s["status"],
        ])
    writer.writerow([])
    writer.writerow(["TOTAL", "", sum(s["tonnes"] for s in CBAM_SHIPMENTS), "", sum(s["carbonCost"] for s in CBAM_SHIPMENTS), "", ""])
    log_activity("CBAM Q3 declaration CSV exported")
    return StreamingResponse(
        iter([buf.getvalue()]),
        media_type="text/csv",
        headers={"Content-Disposition": 'attachment; filename="CBAM_Declaration_Q3_2026.csv"'},
    )
