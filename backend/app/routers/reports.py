import csv
import io

from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse

from app.config import SUPABASE_CONFIGURED
from app.db import get_supabase
from app.auth import get_current_user
from app.pdf import build_pdf
from app.mock_data import (
    BRSR_PRINCIPLES, BRSR_CATEGORY_SCORES, CBAM_SHIPMENTS, COMPANY,
    KPIS, SCOPE_BREAKDOWN, FACILITY_EMISSIONS, EMISSIONS_TREND,
    log_activity,
)

router = APIRouter(prefix="/api/reports", tags=["reports"])


def _brsr_completeness() -> int:
    return round(sum(p["completeness"] for p in BRSR_PRINCIPLES) / len(BRSR_PRINCIPLES))


# ---- BRSR ----

@router.get("/brsr")
def get_brsr(user: dict = Depends(get_current_user)):
    if SUPABASE_CONFIGURED:
        sb = get_supabase()
        result = sb.table("brsr_reports").select("*").eq("company_id", user["company_id"]).execute()
        if result.data:
            return result.data[0]
    return {
        "company": COMPANY,
        "categoryScores": BRSR_CATEGORY_SCORES,
        "principles": BRSR_PRINCIPLES,
        "completeness": _brsr_completeness(),
        "status": "draft",
    }


@router.post("/brsr/generate")
def generate_brsr(user: dict = Depends(get_current_user)):
    completeness = _brsr_completeness()
    record = {
        "company_id": user["company_id"],
        "status": "generated",
        "completeness": completeness,
        "principles": BRSR_PRINCIPLES,
        "category_scores": BRSR_CATEGORY_SCORES,
    }
    if SUPABASE_CONFIGURED:
        sb = get_supabase()
        result = sb.table("brsr_reports").upsert(record, on_conflict="company_id").execute()
        generated = result.data[0]
    else:
        generated = record
    log_activity("BRSR report regenerated (Section C principle data refreshed)")
    return generated


